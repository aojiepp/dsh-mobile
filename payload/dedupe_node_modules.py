# dedupe_node_modules.py — 去重 npm 嵌套 node_modules 里的大副本（payload 第 3 步）
#
# 背景：dsh 0.2.1-rc.2 起 50 个 @deepseek-ai 包把 zod 精确锁在 4.4.3，而顶层被
# hoist 成 4.6.7（来自 ^4.x 区间）→ npm 在每个包下再塞一份 zod@4.4.3
# （51 份 × 2.89MB ≈ 148MB，zip 白胖 40MB+）。桌面版是 pnpm 硬链接看不出来，
# 我们打 payload 要真文件，必须自己收。
#
# 做法（保证每个 importer 解析到的 zod 版本与去重前完全一致）：
#   1. 扫出所有「代码里 import zod」的包，记下它们当前解析到的版本；
#   2. 把顶层那份挪走暂存；
#   3. 提一份嵌套 4.4.3 到顶层，删掉其余嵌套 4.4.3 副本；
#   4. 给「原先解析到顶层版本」的那些 importer 各自塞一份原版本（4.6.7）。
#
# 用法: python payload/dedupe_node_modules.py [dsh-app 根目录]
import json
import os
import re
import shutil
import sys

TEMP = os.environ.get("TEMP", "/tmp")
ZOD_IMPORT = re.compile(r"""from\s+["']zod["']|require\(["']zod["']\)|import\s*\(\s*["']zod["']\s*\)""")
SKIP_DIRS = {"node_modules", "test", "tests", "__tests__", ".git"}


def read_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def version_of(pkgdir):
    return (read_json(os.path.join(pkgdir, "package.json")) or {}).get("version")


def resolve_zod(start):
    p = start
    while True:
        cand = os.path.join(p, "node_modules", "zod")
        if os.path.isdir(cand):
            return cand
        parent = os.path.dirname(p)
        if parent == p:
            return None
        p = parent


def uses_zod(pkgdir):
    for dp, dns, fns in os.walk(pkgdir):
        dns[:] = [d for d in dns if d not in SKIP_DIRS]
        for fn in fns:
            if fn.endswith((".js", ".mjs", ".cjs")):
                try:
                    with open(os.path.join(dp, fn), encoding="utf-8", errors="ignore") as fh:
                        if ZOD_IMPORT.search(fh.read()):
                            return True
                except Exception:
                    pass
    return False


def find_nested_zod(nm):
    out = []
    for dp, dns, _ in os.walk(nm):
        if os.path.basename(dp) == "node_modules" and "zod" in dns:
            out.append(os.path.join(dp, "zod"))
    return out


def dir_size(path):
    total = 0
    for dp, _, fns in os.walk(path):
        for fn in fns:
            try:
                total += os.path.getsize(os.path.join(dp, fn))
            except OSError:
                pass
    return total


def main():
    app = sys.argv[1] if len(sys.argv) > 1 else os.path.join(TEMP, "dshm-trim", "app")
    nm = os.path.join(app, "node_modules")
    top_zod = os.path.join(nm, "zod")
    if not os.path.isdir(top_zod):
        raise SystemExit("top-level zod not found: " + top_zod)
    top_ver = version_of(top_zod)

    nested = [p for p in find_nested_zod(nm) if os.path.normpath(p) != os.path.normpath(top_zod)]
    print("top-level zod:", top_ver, "| nested copies:", len(nested))
    if not nested:
        print("nothing to dedupe")
        return
    vers = sorted({version_of(p) for p in nested})
    print("nested zod versions:", vers)
    if len(vers) != 1:
        raise SystemExit("refusing: nested zod versions are not uniform")

    # --- 1. 扫 importer，记录解析结果 ---
    before = {}
    needs_top_version = []
    for dp, dns, fns in os.walk(nm):
        if "package.json" not in fns or os.path.basename(dp) == "node_modules":
            continue
        j = read_json(os.path.join(dp, "package.json"))
        name = (j or {}).get("name")
        if not name:
            continue
        if os.path.normpath(dp) == os.path.normpath(top_zod):
            continue  # zod 自己不算 importer（否则会给自己套一份副本）
        if not uses_zod(dp):
            continue
        z = resolve_zod(dp)
        ver = version_of(z) if z else "MISSING"
        before[dp] = ver
        if z and os.path.normpath(z) == os.path.normpath(top_zod):
            needs_top_version.append(dp)
    print("zod importers:", len(before),
          "| resolving to top-level:", len(needs_top_version))

    # --- 2. 顶层暂存，提升一份嵌套副本 ---
    if top_ver == vers[0]:
        stash = None
        promoted = top_zod
    else:
        stash = os.path.join(TEMP, "dshm-trim", "_zod_stash_" + str(top_ver))
        shutil.rmtree(stash, ignore_errors=True)
        shutil.move(top_zod, stash)
        promoted = nested.pop(0)
        shutil.move(promoted, top_zod)

    # --- 3. 删掉其余嵌套副本 ---
    removed = 0
    for p in nested:
        removed += dir_size(p)
        shutil.rmtree(p, ignore_errors=True)
        parent = os.path.dirname(p)  # <pkg>/node_modules
        try:
            if not os.listdir(parent):
                os.rmdir(parent)
        except OSError:
            pass
    print("promoted zod %s to top-level; removed %d copies (%.1f MB)"
          % (vers[0], len(nested), removed / 1048576))

    # --- 4. 把暂存版本塞回原解析到顶层的那批 importer ---
    if stash is not None:
        for pkg in needs_top_version:
            dst_nm = os.path.join(pkg, "node_modules")
            os.makedirs(dst_nm, exist_ok=True)
            dst = os.path.join(dst_nm, "zod")
            shutil.rmtree(dst, ignore_errors=True)
            shutil.copytree(stash, dst)
            print("  nested zod %s back under %s" % (
                top_ver, os.path.relpath(pkg, nm)))
        shutil.rmtree(stash, ignore_errors=True)

    # --- 5. 复核：每个 importer 解析版本必须与去重前一致 ---
    bad = 0
    for dp, ver_before in before.items():
        z = resolve_zod(dp)
        ver_after = version_of(z) if z else "MISSING"
        if ver_after != ver_before:
            bad += 1
            print("  MISMATCH:", os.path.relpath(dp, nm), ver_before, "->", ver_after)
    print("verify: %d importers, %d mismatches" % (len(before), bad))
    if bad:
        raise SystemExit("dedupe verification failed")


if __name__ == "__main__":
    main()
